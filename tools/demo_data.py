def seed_otel(conn: Any, now: datetime, rng: random.Random, by_title: dict[str, str]) -> None:
    """Telemetry on top of the transcripts: what the JSONL alone cannot show.

    The main-work numbers mirror the ingested turns (a couple of per cent higher, as in
    life); the service spend, permission decisions, hooks and tool durations are the
    events the dashboard's "beyond the transcripts" widget and the session screen read.
    """
    day_start = local_day_start(now)
    sessions = list(by_title.values())

    def metric(name: str, ts: datetime, value: float, kind: str | None, **attrs: Any) -> None:
        conn.execute(
            "INSERT INTO otel_metrics (key, name, ts, session_id, model, kind, value, attrs)"
            " VALUES (?, ?, ?, ?, ?, ?, ?, ?)",
            (
                uuid.UUID(int=rng.getrandbits(128), version=4).hex,
                name,
                _stamp(ts),
                attrs.pop("session_id", rng.choice(sessions)),
                attrs.pop("model", None),
                kind,
                value,
                json.dumps(attrs),
            ),
        )

    def event(name: str, ts: datetime, **attrs: Any) -> None:
        conn.execute(
            "INSERT INTO otel_events (key, name, ts, session_id, attrs) VALUES (?, ?, ?, ?, ?)",
            (
                uuid.UUID(int=rng.getrandbits(128), version=4).hex,
                name,
                _stamp(ts),
                attrs.pop("session_id", rng.choice(sessions)),
                json.dumps(attrs),
            ),
        )

    def today(minutes_back_max: int = 480) -> datetime:
        at = now - timedelta(minutes=rng.uniform(2, minutes_back_max))
        return max(at, day_start)

    # The main work, mirrored from the ingested turns per model - telemetry sees a
    # couple of per cent more than the transcripts (service traffic rides along).
    rows = conn.execute(
        """
        SELECT model, SUM(input_tokens) AS inp, SUM(output_tokens) AS out,
               SUM(cache_read) AS red, SUM(cache_write_5m + cache_write_1h) AS wrt,
               SUM(cost_usd) AS cost
          FROM turns WHERE ts >= ? GROUP BY model
        """,
        (_stamp(day_start),),
    ).fetchall()
    for row in rows:
        for kind, value in (
            ("input", row["inp"]),
            ("output", row["out"]),
            ("cacheRead", row["red"]),
            ("cacheCreation", row["wrt"]),
        ):
            metric(
                "claude_code.token.usage",
                today(),
                round(value * 1.02),
                kind,
                model=row["model"],
                query_source="main",
            )
        metric(
            "claude_code.cost.usage",
            today(),
            row["cost"] * 1.02,
            None,
            model=row["model"],
            query_source="main",
        )

    # The service spend: session titles and SDK helpers - absent from the JSONL entirely.
    for _ in range(18):
        cost = rng.uniform(0.0004, 0.0009)
        event(
            "api_request",
            today(),
            query_source="generate_session_title",
            model="claude-haiku-4-5-20251001",
            cost_usd=round(cost, 6),
            duration_ms=rng.randint(600, 1_800),
        )
    for _ in range(8):
        event(
            "api_request",
            today(),
            query_source="sdk",
            model="claude-haiku-4-5-20251001",
            cost_usd=round(rng.uniform(0.01, 0.05), 6),
            duration_ms=rng.randint(2_000, 9_000),
        )
    for kind, value in (("input", 28_000), ("output", 5_200), ("cacheRead", 190_000)):
        metric(
            "claude_code.token.usage",
            today(),
            value,
            kind,
            model="claude-haiku-4-5-20251001",
            query_source="auxiliary",
        )
    metric(
        "claude_code.cost.usage",
        today(),
        0.24,
        None,
        model="claude-haiku-4-5-20251001",
        query_source="auxiliary",
    )

    # Permission decisions: mostly the config answers, a human confirms the rest by hand.
    manual = [
        ("Bash", "user_permanent", 7),
        ("Edit", "user_temporary", 6),
        ("WebFetch", "user_permanent", 3),
    ]
    for tool, source, count in manual:
        for _ in range(count):
            event("tool_decision", today(), tool_name=tool, source=source, decision="allow")
    for _ in range(2):
        event("tool_decision", today(), tool_name="Bash", source="user_reject", decision="reject")
    for _ in range(70):
        tool = rng.choice(["Read", "Edit", "Bash", "Grep", "Glob", "Write"])
        event("tool_decision", today(), tool_name=tool, source="config", decision="allow")
    for mode in ("acceptEdits", "acceptEdits", "plan"):
        event("permission_mode_changed", today(), to_mode=mode)

    # A few rate-limit retries: they cost time and never reach the transcript.
    for status in ("429", "429", "429", "529"):
        event("api_error", today(), status_code=status, model="claude-sonnet-5")

    # Hooks: fast tool guards and two slow HTTP ones on the prompt path.
    for hook, runs, low, high in (
        ("PreToolUse", 64, 4, 14),
        ("PostToolUse", 64, 3, 9),
        ("UserPromptSubmit", 18, 180, 650),
        ("Stop", 12, 300, 1_900),
    ):
        for _ in range(runs):
            event(
                "hook_execution_complete",
                today(),
                hook_event=hook,
                total_duration_ms=rng.randint(low, high),
                num_cancelled=0,
                num_non_blocking_error=0,
            )
        event("hook_registered", today(), hook_event=hook, hook_type="command")

    # What came out of the spend today.
    metric("claude_code.lines_of_code.count", today(), 1_284, "added")
    metric("claude_code.lines_of_code.count", today(), 402, "removed")
    metric("claude_code.active_time.total", today(), 4_620, "user")
    metric("claude_code.active_time.total", today(), 6_480, "cli")
    metric("claude_code.commit.count", today(), 11, None)

    # Tool durations for the gift-card session: the session screen shows time in tools.
    gift = by_title["Gift card support"]
    for tool, calls, low, high in (
        ("Bash", 21, 900, 41_000),
        ("Read", 34, 80, 600),
        ("Edit", 18, 90, 400),
        ("Grep", 12, 60, 500),
        ("WebFetch", 3, 2_000, 12_000),
    ):
        for _ in range(calls):
            event(
                "tool_result",
                now - timedelta(hours=rng.uniform(3.5, 4.6)),
                session_id=gift,
                tool_name=tool,
                duration_ms=rng.randint(low, high),
                success="true",
            )


FOLLOW_UPS = [
    "good, keep going",
    "now the edge cases",
    "run the tests again",
    "tighten the types while you are in there",
    "and the same fix on the admin side",
]


def tick(root: Path) -> None:
    """Append a fresh burst to the live sessions so the needle is up for a screenshot."""
    state_path = root / "state.json"
    if not state_path.exists():
        sys.exit(f"{state_path} missing - generate the dataset first")
    state = json.loads(state_path.read_text(encoding="utf-8"))
    now = datetime.now(UTC)
    rng = random.Random()
    for entry in state:
        if entry["kind"] == "permission":
            continue  # it hangs on purpose
        tr = Transcript(
            rng, entry["id"], entry["project"], entry["branch"], entry["model"], entry["entrypoint"]
        )
        tr.last_uuid = entry["last_uuid"]
        tr.context = entry["context"]
        if entry["kind"] == "working":
            at = now - timedelta(seconds=75)
            if entry.get("pending_tool"):
                tr.tool_result(at, entry["pending_tool"])
                at += timedelta(seconds=rng.uniform(2, 4))
            for _ in range(2):
                ids = tr.turn(at, output=rng.randint(150, 800), tools=[tr.pick_tool()])
                at += timedelta(seconds=rng.uniform(3, 8))
                tr.tool_result(at, ids[0])
                at += timedelta(seconds=rng.uniform(2, 5))
            tr.turn(at, output=rng.randint(400, 1_400))
            at += timedelta(seconds=rng.uniform(4, 8))
            tr.prompt(at, rng.choice(FOLLOW_UPS))
            pending = tr.turn(
                now - timedelta(seconds=3),
                output=rng.randint(100, 400),
                tools=[("Bash", {"command": rng.choice(BASH[entry["project"]])})],
            )
            entry["pending_tool"] = pending[0]
        else:  # answered: a fresh question, a fresh answer, still waiting for the human
            tr.prompt(now - timedelta(seconds=40), rng.choice(FOLLOW_UPS))
            tr.turn(now - timedelta(seconds=25), output=rng.randint(500, 1_500))
        tr.append(root)
        entry["last_uuid"] = tr.last_uuid
        entry["context"] = tr.context
    state_path.write_text(json.dumps(state, indent=2), encoding="utf-8")
    print("live sessions refreshed")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=DEFAULT_ROOT, help="demo root directory")
    parser.add_argument("--tick", action="store_true", help="refresh the live sessions only")
    args = parser.parse_args()
    if args.tick:
        tick(args.root)
    else:
        generate(args.root)


if __name__ == "__main__":
    main()
