def _stamp(at: datetime) -> str:
    return f"{at:%Y-%m-%dT%H:%M:%S}.{at.microsecond // 1000:03d}Z"


class Transcript:
    """One JSONL transcript, written the way Claude Code 2.1.x writes it.

    Records accumulate with datetimes and are shifted as a whole on `write`, so a
    session is authored forward and then anchored by its last record ("ends 45 s ago").
    """

    def __init__(
        self,
        rng: random.Random,
        session_id: str,
        project: str,
        branch: str,
        model: str,
        entrypoint: str = "cli",
    ) -> None:
        self.rng = rng
        self.id = session_id
        self.project = project
        self.cwd = f"{HOME}/code/{project}"
        self.branch = branch
        self.model = model
        self.entrypoint = entrypoint
        self.records: list[tuple[datetime, dict[str, Any]]] = []
        self.bare: list[dict[str, Any]] = []  # title and last-prompt records carry no time
        self.last_uuid: str | None = None
        self.context = 0

    def _hex(self, length: int) -> str:
        return "".join(self.rng.choice("0123456789abcdef") for _ in range(length))

    def _uuid(self) -> str:
        return str(uuid.UUID(int=self.rng.getrandbits(128), version=4))

    def _record(self, at: datetime, body: dict[str, Any], sidechain: bool = False) -> None:
        record = {
            "parentUuid": self.last_uuid,
            "isSidechain": sidechain,
            "userType": "external",
            "entrypoint": self.entrypoint,
            "cwd": self.cwd,
            "sessionId": self.id,
            "version": VERSION,
            "gitBranch": self.branch,
            "uuid": self._uuid(),
            **body,
        }
        self.last_uuid = record["uuid"]
        self.records.append((at, record))

    def prompt(self, at: datetime, text: str, compact: bool = False) -> None:
        body: dict[str, Any] = {"type": "user", "message": {"role": "user", "content": text}}
        if compact:
            body["isCompactSummary"] = True
        self._record(at, body)

    def tool_result(self, at: datetime, tool_use_id: str, sidechain: bool = False) -> None:
        content = [{"tool_use_id": tool_use_id, "type": "tool_result", "content": "[result]"}]
        self._record(
            at, {"type": "user", "message": {"role": "user", "content": content}}, sidechain
        )

    def turn(
        self,
        at: datetime,
        output: int,
        tools: list[tuple[str, dict[str, Any]]] | None = None,
        sidechain: bool = False,
        model: str | None = None,
        read: int | None = None,
        write_1h: int = 0,
    ) -> list[str]:
        """One model answer: a text record plus a record per tool_use, identical usage."""
        if read is None:
            read = self.context
            if not self.context and not write_1h:
                write_1h = self.rng.randint(16_000, 22_000)  # first turn caches the system prompt
            write_5m = self.rng.randint(400, 3_500) if self.context else 0
            self.context = read + write_5m + write_1h + output
        else:
            write_5m = self.rng.randint(200, 1_200)  # a sidechain grows its own small context
        usage = {
            "input_tokens": self.rng.randint(2, 9),
            "cache_creation_input_tokens": write_5m + write_1h,
            "cache_read_input_tokens": read,
            "output_tokens": output,
            "service_tier": "standard",
            "cache_creation": {
                "ephemeral_5m_input_tokens": write_5m,
                "ephemeral_1h_input_tokens": write_1h,
            },
        }
        message_id = "msg_" + self._hex(24)
        request_id = "req_" + self._hex(24)
        blocks: list[dict[str, Any]] = [{"type": "text", "text": "[answer]"}]
        tool_ids: list[str] = []
        for name, tool_input in tools or []:
            tool_id = "toolu_" + self._hex(22)
            tool_ids.append(tool_id)
            blocks.append({"type": "tool_use", "id": tool_id, "name": name, "input": tool_input})
        for index, block in enumerate(blocks):
            message = {
                "model": model or self.model,
                "id": message_id,
                "type": "message",
                "role": "assistant",
                "content": [block],
                "stop_reason": "tool_use" if tool_ids else "end_turn",
                "stop_sequence": None,
                "usage": usage,
            }
            body = {"type": "assistant", "requestId": request_id, "message": message}
            self._record(at + timedelta(milliseconds=350 * index), body, sidechain)
        return tool_ids

    def pick_tool(self) -> tuple[str, dict[str, Any]]:
        name = self.rng.choices([n for n, _ in TOOLS], [w for _, w in TOOLS])[0]
        if name == "Bash":
            return name, {"command": self.rng.choice(BASH[self.project])}
        return name, {}

    def title(self, text: str) -> None:
        self.bare.append({"type": "ai-title", "aiTitle": text, "sessionId": self.id})

    def last_prompt(self, text: str) -> None:
        record = {"type": "last-prompt", "lastPrompt": text, "leafUuid": self.last_uuid}
        self.bare.append({**record, "sessionId": self.id})

    def path(self, root: Path) -> Path:
        slug = f"{HOME}/code/{self.project}".replace("/", "-")
        return root / "claude" / "projects" / slug / f"{self.id}.jsonl"

    def write(self, root: Path, end_at: datetime) -> None:
        """Anchor the session so its last record lands at `end_at`, then write the file."""
        shift = end_at - self.records[-1][0]
        path = self.path(root)
        path.parent.mkdir(parents=True, exist_ok=True)
        with path.open("w", encoding="utf-8") as fh:
            for at, record in self.records:
                fh.write(json.dumps({**record, "timestamp": _stamp(at + shift)}) + "\n")
            for record in self.bare:
                fh.write(json.dumps(record) + "\n")

    def append(self, root: Path) -> None:
        """Append the accumulated records as they are - the `--tick` path."""
        with self.path(root).open("a", encoding="utf-8") as fh:
            for at, record in self.records:
                fh.write(json.dumps({**record, "timestamp": _stamp(at)}) + "\n")


def build_session(tr: Transcript, spec: dict[str, Any]) -> str | None:
    """Author the whole conversation; return the pending tool_use id for a live tail."""
    rng = tr.rng
    at = datetime(2026, 1, 1, tzinfo=UTC)  # any base: `write` anchors by the last record
    hot = spec.get("live") == "working"
    for index, text in enumerate(spec["prompts"]):
        if index == spec.get("compact_at"):
            summary = "This session is being continued from a previous conversation..."
            tr.prompt(at, summary, compact=True)
            tr.context = 30_000  # the compaction collapses the context
            at += timedelta(seconds=rng.uniform(15, 40))
        tr.prompt(at, text)
        at += timedelta(seconds=rng.uniform(4, 10))
        idle = index in spec.get("idle_at", ())
        for _ in range(0 if idle else rng.randint(3, 6) if hot else rng.randint(2, 5)):
            ids = tr.turn(at, output=rng.randint(90, 700), tools=[tr.pick_tool()])
            at += timedelta(seconds=rng.uniform(2, 8) if hot else rng.uniform(3, 25))
            tr.tool_result(at, ids[0])
            at += timedelta(seconds=rng.uniform(1, 6))
        if index == spec.get("sidechain_at"):
            at = _sidechain(tr, at)
        tr.turn(at, output=rng.randint(4, 8) if idle else rng.randint(300, 2_200))
        at += timedelta(seconds=rng.uniform(15, 60) if hot else rng.uniform(25, 240))
    pending: str | None = None
    if spec.get("live") in ("working", "permission"):
        tr.prompt(at, spec["live_prompt"])
        at += timedelta(seconds=rng.uniform(4, 9))
        pending = tr.turn(
            at, output=rng.randint(100, 400), tools=[("Bash", {"command": spec["live_command"]})]
        )[0]
    tr.title(spec["title"])
    tr.last_prompt(spec["prompts"][-1] if not pending else spec["live_prompt"])
    return pending


def _sidechain(tr: Transcript, at: datetime) -> datetime:
    """A Task fan-out: a few haiku turns living in the parent file, marked isSidechain."""
    rng = tr.rng
    ids = tr.turn(at, output=rng.randint(100, 300), tools=[("Task", {})])
    at += timedelta(seconds=rng.uniform(2, 5))
    read = 8_000
    for _ in range(3):
        side = tr.turn(
            at,
            output=rng.randint(200, 900),
            tools=[("Grep", {})],
            sidechain=True,
            model="claude-haiku-4-5-20251001",
            read=read,
        )
        at += timedelta(seconds=rng.uniform(2, 6))
        tr.tool_result(at, side[0], sidechain=True)
        at += timedelta(seconds=rng.uniform(1, 4))
        read += rng.randint(2_000, 5_000)
    tr.tool_result(at, ids[0])
    return at + timedelta(seconds=rng.uniform(1, 4))


