def generate(root: Path) -> None:
    if root.exists():
        if not (root / MARKER).exists():
            sys.exit(f"{root} exists and does not look like a demo root ({MARKER} missing)")
        shutil.rmtree(root)
    root.mkdir(parents=True)
    (root / "data").mkdir()
    (root / MARKER).touch()
    (root / "config.toml").write_text(CONFIG_TOML, encoding="utf-8")

    now = datetime.now(UTC)
    rng = random.Random(20260819)
    state: list[dict[str, Any]] = []
    sessions: list[tuple[dict[str, Any], Transcript]] = []
    for spec in sessions_spec():
        tr = Transcript(
            rng,
            str(uuid.UUID(int=rng.getrandbits(128), version=4)),
            spec["project"],
            spec["branch"],
            spec["model"],
            spec.get("entrypoint", "cli"),
        )
        pending = build_session(tr, spec)
        tr.write(root, now - spec["end"])
        sessions.append((spec, tr))
        if spec.get("live"):
            state.append(
                {
                    "kind": spec["live"],
                    "file": str(tr.path(root)),
                    "id": tr.id,
                    "project": spec["project"],
                    "cwd": tr.cwd,
                    "branch": tr.branch,
                    "model": tr.model,
                    "entrypoint": tr.entrypoint,
                    "last_uuid": tr.last_uuid,
                    "context": tr.context,
                    "pending_tool": pending,
                }
            )
    (root / "state.json").write_text(json.dumps(state, indent=2), encoding="utf-8")

    conn = db.connect(root / "data" / "cburn.db")
    try:
        pricing.sync_prices(conn, config.load(root / "config.toml"))
        ingest_tree(conn, root / "claude" / "projects")
        by_title = {spec["title"]: tr.id for spec, tr in sessions}
        with conn:
            seed_advice(conn, now, by_title)
            seed_otel(conn, now, rng, by_title)
        turns, cost = conn.execute("SELECT COUNT(*), SUM(cost_usd) FROM turns").fetchone()
        print(f"demo root: {root}")
        print(f"sessions: {len(sessions)}, turns: {turns}, cost: ${cost:.2f}")
    finally:
        conn.close()
    print("serve it with:")
    print(
        f"  CLAUDE_CONFIG_DIR={root}/claude CBURN_CONFIG={root}/config.toml"
        f" CBURN_DATA_DIR={root}/data .venv/bin/cburn serve"
    )


